export type DivergenceStatus = "intentional" | "pending-port" | "pending-decision" | "unreviewed-gap";

export const DIVERGENCE_STATUSES: readonly DivergenceStatus[] = [
  "intentional",
  "pending-port",
  "pending-decision",
  "unreviewed-gap",
];

export interface AcceptedDivergence {
  tool: string;
  param: string | null;
  kind: DivergenceKind;
  observed: string;
  status: DivergenceStatus;
  reason: string;
}

export interface NormalizationRule {
  enabled: boolean;
  status: DivergenceStatus;
  reason: string;
}

export interface Ratchet {
  unreviewedGaps: number;
}

export interface Registry {
  normalization: Record<NormalizationRuleName, NormalizationRule>;
  ratchet: Ratchet;
  divergences: AcceptedDivergence[];
}

/**
 * The status the registry is not allowed to accumulate: a difference the comparator
 * found and nobody has ruled on. Everything else is somebody's decision and can be
 * argued with; this one is just a pile.
 */
export const RATCHETED_STATUS: DivergenceStatus = "unreviewed-gap";

/**
 * How many divergences of the ratcheted status the registry says it may hold.
 * Read rather than reached for, so everything that shows this number -- the check
 * and the report -- refuses the same unreadable registry with the same words.
 */
export function ratchetCeiling(registry: Registry): number {
  const node = registry as unknown as Record<string, unknown>;
  const declared = (read(node, "ratchet", "object", "the registry") ?? {}) as Record<
    string,
    unknown
  >;
  const allowed = read(declared, "unreviewedGaps", "count", "the registry's ratchet");
  if (allowed === undefined) {
    throw new Error(
      `the registry does not say how many "${RATCHETED_STATUS}" divergences it may hold, and ` +
        "that number is the only thing stopping the pile growing",
    );
  }
  return allowed as number;
}

/**
 * What the ratchet has to say about the registry as it stands.
 *
 * Counted over the registry's own entries rather than over the live divergences,
 * which is the same number: the two tests either side of this one fail the moment
 * the registry lists a divergence the surfaces no longer support or misses one they
 * do. A malformed declaration throws instead -- a count that cannot be read is not
 * a parity problem, it is a registry nobody can check.
 */
export function ratchetProblems(registry: Registry): string[] {
  const ceiling = ratchetCeiling(registry);
  const held = registry.divergences.filter((d) => d.status === RATCHETED_STATUS).length;
  if (held > ceiling) {
    return [
      `the registry holds ${held} "${RATCHETED_STATUS}" divergences where ${ceiling} is the most ` +
        "it may hold. A new one needs somebody to read both sides and give it a reviewed status " +
        "and a reason, or the gap closed in the op -- not a bigger number in `ratchet`.",
    ];
  }
  if (held < ceiling) {
    return [
      `the registry holds ${held} "${RATCHETED_STATUS}" divergences and says it may hold ` +
        `${ceiling}. Lower \`ratchet.unreviewedGaps\` to ${held}: a number left above the real ` +
        "count is room for the next one to arrive unnoticed.",
    ];
  }
  return [];
}

/** One tool deliberately left without a fixture, and why. */
export interface FixtureExclusion {
  tool: string;
  reason: string;
}

/**
 * The coverage half of the registry: how many open tools have no golden case, and which
 * tools are allowed to have none.
 *
 * Not a divergence section. A divergence is a difference somebody found between the two
 * surfaces; this is a statement about how much of the surface anybody has LOOKED at, which
 * is the thing a divergence count cannot tell you. It ratchets the same way: the number is
 * held to the real count in both directions, so it cannot drift and cannot quietly grow.
 */
export interface FixtureCoverage {
  source: string;
  uncoveredTools: number;
  excluded: FixtureExclusion[];
}

export function fixtureCoverage(registry: Registry): FixtureCoverage {
  const node = registry as unknown as Record<string, unknown>;
  const section = read(node, "fixtures", "object", "the registry") as FixtureCoverage | undefined;
  if (!section) {
    throw new Error(
      'the registry has no "fixtures" section, and nothing then says how much of the ' +
        "surface is compared against the other server at all",
    );
  }
  const where = 'the registry\'s "fixtures" section';
  const held = read(section as unknown as Record<string, unknown>, "uncoveredTools", "count", where);
  if (held === undefined) {
    throw new Error(`${where} does not say how many open tools it allows to have no case`);
  }
  if (!Array.isArray(section.excluded)) {
    throw new Error(`${where} does not list the tools it excludes`);
  }
  for (const [index, entry] of section.excluded.entries()) {
    const at = `${where}, exclusion ${index}`;
    if (!isPlainObject(entry)) throw new Error(`${at} is ${describeValue(entry)}, not an exclusion`);
    if (read(entry, "tool", "string", at) === undefined) throw new Error(`${at} names no tool`);
    if (read(entry, "reason", "string", at) === undefined) throw new Error(`${at} gives no reason`);
  }
  return section;
}

/** How many golden cases each tool has, read off the generated index. */
export function loadFixtureCounts(): Map<string, number> {
  const index = readJson<{ cases: { tool: string }[] }>(ENVELOPE_INDEX_URL, "golden case index");
  const node = index as unknown as Record<string, unknown>;
  const cases = read(node, "cases", "list", "the golden case index");
  if (cases === undefined) throw new Error("the golden case index lists no cases");
  const counts = new Map<string, number>();
  for (const [position, entry] of (cases as unknown[]).entries()) {
    const where = `the golden case index's case ${position}`;
    if (!isPlainObject(entry)) throw new Error(`${where} is ${describeValue(entry)}, not a case`);
    const tool = read(entry, "tool", "string", where);
    if (tool === undefined) throw new Error(`${where} names no tool`);
    counts.set(tool as string, (counts.get(tool as string) ?? 0) + 1);
  }
  return counts;
}

/**
 * What the coverage ratchet has to say about the tools as they stand.
 *
 * Three ways to fail, and the third is the one that keeps the exclusion list honest: an
 * open tool with no case, a number that no longer matches how many of those there are, and
 * an excluded tool that has a case after all -- which means somebody fixtured it and left
 * the excuse behind.
 */
export function fixtureProblems(
  registry: Registry,
  tools: Iterable<string>,
  counts: Map<string, number>,
): string[] {
  const coverage = fixtureCoverage(registry);
  const excluded = new Map(coverage.excluded.map((e) => [e.tool, e.reason]));
  const problems: string[] = [];
  const all = [...tools].sort();

  const unknown = [...excluded.keys()].filter((tool) => !all.includes(tool)).sort();
  if (unknown.length > 0) {
    problems.push(
      `the fixtures section excludes ${unknown.join(", ")}, which this server does not ` +
        "serve; an exclusion nobody can check is an exclusion nobody will notice going stale.",
    );
  }
  const fixtured = [...excluded.keys()].filter((tool) => (counts.get(tool) ?? 0) > 0).sort();
  if (fixtured.length > 0) {
    problems.push(
      `${fixtured.join(", ")} has golden cases and is still listed as excluded. Drop the ` +
        "exclusion: it is now an excuse for something nobody is doing.",
    );
  }
  const uncovered = all.filter((tool) => !excluded.has(tool) && (counts.get(tool) ?? 0) === 0);
  if (uncovered.length > coverage.uncoveredTools) {
    problems.push(
      `${uncovered.join(", ")} ${uncovered.length === 1 ? "has" : "have"} no golden case, ` +
        `where ${coverage.uncoveredTools} uncovered tool(s) is the most this registry allows. ` +
        "A tool nobody compares is a tool the two surfaces can answer differently for ever -- " +
        "write the cases, or exclude it with a reason, not with a bigger number.",
    );
  } else if (uncovered.length < coverage.uncoveredTools) {
    problems.push(
      `${uncovered.length} open tool(s) have no golden case and the registry says ` +
        `${coverage.uncoveredTools} may. Lower \`fixtures.uncoveredTools\` to ` +
        `${uncovered.length}: a number left above the real count is room for the next tool to ` +
        "arrive uncompared.",
    );
  }
  return problems;
}

function readJson<T>(url: URL, what: string): T {
  const path = fileURLToPath(url);
  try {
    return JSON.parse(readFileSync(path, "utf8")) as T;
  } catch (err) {
    throw new Error(`cannot read the ${what} at ${path}: ${(err as Error).message}`);
  }
}

